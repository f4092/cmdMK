def prepare_terminal():
    """Set up terminal input and ANSI output on Windows or Unix."""
    if os.name != "nt":
        fd = sys.stdin.fileno()
        original = termios.tcgetattr(fd)
        updated = termios.tcgetattr(fd)
        updated[3] &= ~(termios.ECHO | termios.ICANON)
        termios.tcsetattr(fd, termios.TCSANOW, updated)
        return ("unix", fd, original)

    kernel32 = ctypes.WinDLL("kernel32", use_last_error=True)
    stdout_handle = kernel32.GetStdHandle(-11)
    stdin_handle = kernel32.GetStdHandle(-10)
    original_modes = []
    for handle, enable, disable in (
        (stdout_handle, 0x0004, 0),  # ENABLE_VIRTUAL_TERMINAL_PROCESSING
        (stdin_handle, 0, 0x0004),   # disable ENABLE_ECHO_INPUT
    ):
        old_mode = wintypes.DWORD()
        if kernel32.GetConsoleMode(handle, ctypes.byref(old_mode)):
            new_mode = (old_mode.value | enable) & ~disable
            if kernel32.SetConsoleMode(handle, new_mode):
                original_modes.append((handle, old_mode.value))
    return ("windows", kernel32, original_modes)


def restore_terminal(settings):
    if settings[0] == "unix":
        _, fd, original = settings
        termios.tcsetattr(fd, termios.TCSADRAIN, original)
    else:
        _, kernel32, original_modes = settings
        for handle, mode in original_modes:
            kernel32.SetConsoleMode(handle, mode)


held_keys = set()
pressed_keys = set()
keys_lock = threading.Lock()


def key_name(key):
    if key == keyboard.Key.space:
        return "space"
    try:
        return key.char.lower()
    except (AttributeError, TypeError):
        return None


def on_press(key):
    name = key_name(key)
    if name is None:
        return
    with keys_lock:
        if name not in held_keys:
            pressed_keys.add(name)
        held_keys.add(name)


def on_release(key):
    name = key_name(key)
    if name is None:
        return
    with keys_lock:
        held_keys.discard(name)


def get_input():
    with keys_lock:
        held = held_keys.copy()
        pressed = pressed_keys.copy()
        pressed_keys.clear()
    return held, pressed


