def sprite_lines(sprite):
    return sprite.strip("\n").splitlines()


def get_sprite_width(sprite):
    return max((len(line.rstrip()) for line in sprite_lines(sprite)), default=0)


def get_sprite_height(sprite):
    return len(sprite_lines(sprite))


class Fighter:
    def __init__(self, name, x, facing, sprites):
        self.name, self.x, self.facing, self.sprites = name, x, facing, sprites
        self.state = "idle"
        self.frame = 0
        self.direction = 1
        self.sprite = sprites["idle"][0]
        self.standing_height = max(map(get_sprite_height, sprites["idle"]))
        self.health = MAX_HEALTH
        self.attack_connected = False
        self.cooldown = 0
        self.jump_cooldown = 0
        self.jump_direction = 0
        self.jump_tick = 0
        self.jump_duration = len(sprites["jump"])
        self.airborne = False
        self.vertical_offset = 0
        self.hit_direction = 1
        self.launch_tick = 0
        self.launch_direction = 0

    def busy(self):
        return self.state in ATTACK_NAMES

    def attack(self, name):
        if (self.health <= 0 or self.busy() or self.state in
                ("duck", "block", "jump", "hit", "launchback") or self.cooldown):
            return False
        self.state, self.frame, self.direction = name, 0, 1
        self.attack_connected = False
        self.cooldown = ATTACK_COOLDOWN_FRAMES
        return True

    def start_jump(self, direction):
        if (self.health <= 0 or self.busy() or self.state in
                ("duck", "block", "hit", "jump", "launchback") or
                self.jump_cooldown or not direction):
            return False
        self.state = "jump"
        self.jump_direction = direction
        self.jump_tick = 0
        self.airborne = True
        self.vertical_offset = 0
        self.jump_cooldown = JUMP_COOLDOWN_FRAMES + self.jump_duration
        return True

    def receive_hit(self, damage, heavy_kick=False, attacker_facing=1):
        self.health = max(0, self.health - damage)
        self.airborne = False
        self.vertical_offset = 0
        self.frame = 0
        self.direction = 1
        self.attack_connected = False
        if heavy_kick:
            self.state = "launchback"
            self.launch_tick = 0
            self.launch_direction = attacker_facing
            self.sprite = self.sprites["launchback"][0]
        else:
            self.state = "hit"
            self.hit_direction = 1
            self.sprite = self.sprites["hit"][0]

    def update(self, move=0, duck=False, block=False):
        self.cooldown = max(0, self.cooldown - 1)
        self.jump_cooldown = max(0, self.jump_cooldown - 1)
        if self.health <= 0:
            self.sprite = self.sprites["idle"][0]
            return
        if self.state == "launchback":
            frames = self.sprites["launchback"]
            self.sprite = frames[min(self.launch_tick, len(frames) - 1)]
            # Distribute knockback across animation, stronger early impulse.
            total = len(frames)
            step = LAUNCH_DISTANCE * (total - self.launch_tick) * 2 / (total * (total + 1))
            self.x += self.launch_direction * step
            self.launch_tick += 1
            if self.launch_tick >= total:
                self.state, self.frame = "idle", 0
            return
        if self.state == "hit":
            frames = self.sprites["hit"]
            self.sprite = frames[self.frame]
            if self.hit_direction == 1:
                if self.frame == len(frames) - 1:
                    self.hit_direction = -1
                    self.frame = max(0, self.frame - 1)
                else:
                    self.frame += 1
            elif self.frame > 0:
                self.frame -= 1
            else:
                self.state, self.frame = "idle", 0
            return
        if self.state == "jump":
            frames = self.sprites["jump"]
            progress = self.jump_tick / max(1, self.jump_duration - 1)
            self.sprite = frames[min(self.jump_tick, len(frames) - 1)]
            self.vertical_offset = round(JUMP_HEIGHT * 4 * progress * (1 - progress))
            self.airborne = self.vertical_offset >= 4
            self.x += self.jump_direction * JUMP_SPEED
            self.jump_tick += 1
            if self.jump_tick >= self.jump_duration:
                self.state, self.frame = "idle", 0
                self.airborne, self.vertical_offset = False, 0
            return
        if self.busy():
            frames = self.sprites[self.state]
            self.sprite = frames[self.frame]
            if self.direction == 1 and self.frame == len(frames) - 1:
                self.direction = -1
            elif self.direction == -1 and self.frame == 0:
                self.state, self.frame, self.direction = "idle", 0, 1
                return
            self.frame += self.direction
            return
        desired_hold = "block" if block else "duck" if duck else None
        if self.state in ("duck", "block"):
            frames = self.sprites[self.state]
            self.sprite = frames[self.frame]
            if desired_hold == self.state:
                self.direction = 1
                self.frame = min(self.frame + 1, len(frames) - 1)
            else:
                self.direction = -1
                if self.frame == 0:
                    self.state, self.frame, self.direction = "idle", 0, 1
                else:
                    self.frame -= 1
            return
        if desired_hold:
            self.state, self.frame, self.direction = desired_hold, 0, 1
            self.sprite = self.sprites[desired_hold][0]
            self.frame = min(1, len(self.sprites[desired_hold]) - 1)
            return
        new_state = ("forward" if move == self.facing else "back") if move else "idle"
        if new_state != self.state:
            self.state, self.frame = new_state, 0
        frames = self.sprites[self.state]
        self.sprite = frames[self.frame % len(frames)]
        self.frame += 1

    def draw(self, canvas, width, height):
        lines = sprite_lines(self.sprite)
        left = round(self.x - get_sprite_width(self.sprite) / 2)
        ground_y = PLAYER_Y + self.standing_height
        top = ground_y - len(lines) - self.vertical_offset
        for y, line in enumerate(lines):
            sy = top + y
            if not 0 <= sy < height:
                continue
            for dx, char in enumerate(line):
                sx = left + dx
                if char != " " and 0 <= sx < width:
                    canvas[sy][sx] = char

class CPUBrain:
    def __init__(self):
        self.intent = "approach"
        self.until = 0
        self.next_attack = 0
        self.next_escape = 0
        self.pressure = 0
        self.last_health = MAX_HEALTH

    def decide(self, tick, cpu, player, arena_width=GAME_WIDTH):
        distance = abs(cpu.x - player.x)
        right_room = arena_width - 20 - cpu.x
        left_room = cpu.x - 20
        threatened = player.busy() and distance <= ATTACK_DATA[player.state]["range"] + 3
        trapped = right_room < 16
        opponent_cornered = player.x < 36
        if cpu.health < self.last_health:
            self.pressure = min(14, self.pressure + 4)
        elif threatened or distance < 30:
            self.pressure = min(14, self.pressure + 1)
        else:
            self.pressure = max(0, self.pressure - 1)
        self.last_health = cpu.health

        if cpu.state == "hit":
            return 0, False, False
        if cpu.state == "launchback" or cpu.state == "jump" or cpu.busy():
            return 0, False, False

        # Counter threatening attacks by blocking, not always jumping.
        if threatened and random.random() < (0.52 if distance < 34 else 0.38):
            self.intent, self.until = "block", tick + random.randint(3, 6)
            return 0, False, True
        if (self.pressure >= 7 and tick >= self.next_escape and
                not trapped and distance < 37 and random.random() < 0.12):
            if cpu.start_jump(1):
                self.next_escape = tick + random.randint(30, 50)
                self.pressure = 0
                self.intent, self.until = "approach", tick + cpu.jump_duration
                return 0, False, False

        if tick >= self.until:
            if distance > 40:
                options, weights = ["approach", "approach", "bait"], [8, 5, 1]
            elif distance > 32:
                options, weights = ["approach", "attack", "block", "bait"], [6, 5, 2, 2]
            else:
                options, weights = ["attack", "approach", "block", "bait", "duck"], [12, 4, 4, 3, 1]
            if trapped:
                options, weights = ["approach", "attack", "block", "duck"], [7, 10, 5, 1]
            if opponent_cornered and distance < 42:
                options, weights = ["attack", "approach", "block", "bait"], [13, 6, 3, 1]
            self.intent = random.choices(options, weights=weights)[0]
            self.until = tick + random.randint(3, 8)

        # Always seize openings in attack range rather than waiting for a new intent.
        can_attack = tick >= self.next_attack and cpu.cooldown == 0 and cpu.state not in ("block", "duck")
        if can_attack and distance <= 38 and (self.intent == "attack" or
                (not threatened and random.random() < 0.19)):
            valid = [name for name, info in ATTACK_DATA.items() if distance <= info["range"]]
            if valid and cpu.attack(random.choice(valid)):
                self.next_attack = tick + random.randint(5, 10)
                self.intent, self.until = "approach", tick + 4
                return 0, False, False
        if self.intent == "bait" and not trapped and distance < 39:
            return 1, False, False
        if self.intent == "block":
            return 0, False, True
        if self.intent == "duck":
            return 0, True, False
        if distance > 27 or self.intent == "approach":
            return -1, False, False
        return 0, False, False


def resolve_attack(attacker, defender, arena_width):
    if not attacker.busy() or attacker.attack_connected or attacker.direction != -1:
        return None
    frames = attacker.sprites[attacker.state]
    if attacker.frame != len(frames) - 2:
        return None
    attack = ATTACK_DATA[attacker.state]
    ahead = (defender.x - attacker.x) * attacker.facing
    if not (MIN_FIGHTER_DISTANCE - 2 <= ahead <= attack["range"]):
        return None
    if defender.airborne and defender.vertical_offset >= 4:
        return None
    if defender.state == "duck" and attack["level"] == "high":
        return None
    # Launchback is uninterruptible, including by a second heavy kick.
    if defender.state == "launchback":
        return None
    blocked = defender.state == "block"
    damage = attack["damage"]
    if blocked:
        damage = max(1, round(damage * BLOCK_DAMAGE_MULTIPLIER))
        defender.health = max(0, defender.health - damage)
        defender.x = max(20, min(arena_width - 20,
            defender.x + attacker.facing * BLOCK_PUSHBACK[attacker.state]))
    else:
        defender.receive_hit(damage, heavy_kick=attacker.state == "heavy_kick",
                             attacker_facing=attacker.facing)
    attacker.attack_connected = True
    return ("BLOCK" if blocked else "HIT", attacker.name, damage)


def put_text(canvas, y, x, message):
    if not 0 <= y < len(canvas):
        return
    for offset, char in enumerate(message):
        sx = x + offset
        if 0 <= sx < len(canvas[y]):
            canvas[y][sx] = char


def render_fighters(player, cpu, event=None, winner=None):
    terminal = shutil.get_terminal_size((GAME_WIDTH, GAME_HEIGHT))
    width = min(GAME_WIDTH, terminal.columns)
    height = min(GAME_HEIGHT, terminal.lines)
    canvas = [[" "] * width for _ in range(height)]

    bar_width = HEALTH_SEGMENTS
    p_full = (player.health * bar_width + MAX_HEALTH - 1) // MAX_HEALTH
    c_full = (cpu.health * bar_width + MAX_HEALTH - 1) // MAX_HEALTH
    # P1 empties from the center toward left; P2 empties from center toward right.
    left_bar = "░" * (bar_width - p_full) + "▉" * p_full
    right_bar = "▉" * c_full + "░" * (bar_width - c_full)
    put_text(canvas, 3, 3, f"P1 {left_bar} {player.health:3d}")
    right_hud = f"{cpu.health:3d} {right_bar} P2"
    put_text(canvas, 3, width - 3 - len(right_hud), right_hud)

    if winner:
        message = f"{winner} WINS!  PRESS Q TO QUIT / R TO RESTART"
        put_text(canvas, 9, max(0, (width - len(message)) // 2), message)

    player.draw(canvas, width, height)
    cpu.draw(canvas, width, height)
    sys.stdout.write("".join(f"\033[{y + 1};1H" + "".join(row) for y, row in enumerate(canvas)))
    sys.stdout.write(f"\033[2;4H\033[1m{player.name}\033[0m")
    sys.stdout.write(f"\033[2;{max(1, width - len(cpu.name) - 2)}H\033[1m{cpu.name}\033[0m")
    sys.stdout.flush()


def main():
    player = Fighter("SUB-ZERO", PLAYER_X, 1, PLAYER_SPRITES)
    cpu = Fighter("SCORPION", CPU_X, -1, CPU_SPRITES)
    brain = CPUBrain()
    tick = 0
    winner = None

    terminal_settings = prepare_terminal()
    sys.stdout.write(f"\033[8;{GAME_HEIGHT};{GAME_WIDTH}t")
    sys.stdout.flush()
    time.sleep(0.2)
    listener = keyboard.Listener(on_press=on_press, on_release=on_release)
    listener.start()
    sys.stdout.write("\033[?1049h\033[?25l\033[2J\033[H")
    sys.stdout.flush()

    try:
        while True:
            frame_start = time.monotonic()
            held, pressed = get_input()
            if "q" in held or "q" in pressed:
                break
            if winner and "r" in pressed:
                player = Fighter("SUB-ZERO", PLAYER_X, 1, PLAYER_SPRITES)
                cpu = Fighter("SCORPION", CPU_X, -1, CPU_SPRITES)
                brain = CPUBrain()
                tick = 0
                winner = None

            if not winner:
                player_move = (1 if "d" in held else 0) - (1 if "a" in held else 0)
                if "w" in held and player_move and ("w" in pressed or
                        "a" in pressed or "d" in pressed):
                    player.start_jump(player_move)
                for key in ("j", "i", "o", "p"):
                    if key in pressed:
                        player.attack(ATTACK_KEYS[key])
                        break

                terminal = shutil.get_terminal_size((GAME_WIDTH, GAME_HEIGHT))
                width = min(GAME_WIDTH, terminal.columns)
                cpu_move, cpu_duck, cpu_block = brain.decide(tick, cpu, player, width)
                player.update(move=player_move, duck="s" in held, block="space" in held)
                cpu.update(move=cpu_move, duck=cpu_duck, block=cpu_block)

                player_step = player_move if player.state in ("forward", "back", "idle") else 0
                cpu_step = cpu_move if cpu.state in ("forward", "back", "idle") else 0
                player.x = max(20, min(width - 20, player.x + player_step * MOVE_SPEED))
                cpu.x = max(20, min(width - 20, cpu.x + cpu_step * CPU_MOVE_SPEED))
                player.x = max(20, min(width - 20, player.x))
                cpu.x = max(20, min(width - 20, cpu.x))
                if cpu.x - player.x < MIN_FIGHTER_DISTANCE:
                    # Preserve left/right ordering without shoving the fighter
                    # currently in an uninterruptible launchback animation.
                    if cpu.state == "launchback" and player.state != "launchback":
                        player.x = cpu.x - MIN_FIGHTER_DISTANCE
                    elif player.state == "launchback" and cpu.state != "launchback":
                        cpu.x = player.x + MIN_FIGHTER_DISTANCE
                    else:
                        midpoint = (cpu.x + player.x) / 2
                        player.x = midpoint - MIN_FIGHTER_DISTANCE / 2
                        cpu.x = midpoint + MIN_FIGHTER_DISTANCE / 2
                    player.x = max(20, min(width - 20, player.x))
                    cpu.x = max(20, min(width - 20, cpu.x))

                resolve_attack(player, cpu, width)
                if cpu.health > 0:
                    resolve_attack(cpu, player, width)

                if player.health <= 0 or cpu.health <= 0:
                    winner = cpu.name if player.health <= 0 else player.name

            render_fighters(player, cpu, winner=winner)
            tick += 1
            elapsed = time.monotonic() - frame_start
            time.sleep(max(0, (1 / FPS) - elapsed))
    except KeyboardInterrupt:
        pass
    finally:
        listener.stop()
        restore_terminal(terminal_settings)
        sys.stdout.write("\033[?25h\033[?1049l")
        sys.stdout.flush()
        print("Mortal Kombat stopped.")


if __name__ == "__main__":
    main()
